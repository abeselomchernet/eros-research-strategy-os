-- C1-r2 additive extension of 009; applies to clean and existing r1 stores.
-- Existing rows are captured as baseline_import, never invented historical reviews.
BEGIN;
LOCK TABLE ontology.indicator_aliases IN SHARE ROW EXCLUSIVE MODE;
ALTER TABLE ontology.indicator_aliases ADD COLUMN IF NOT EXISTS previous_alias_id UUID
  REFERENCES ontology.indicator_aliases(alias_id) ON DELETE RESTRICT;
DO $$ DECLARE c record; BEGIN
  FOR c IN SELECT conname FROM pg_constraint
    WHERE conrelid='ontology.indicator_aliases'::regclass AND contype='u'
    AND pg_get_constraintdef(oid)='UNIQUE (provider_id, provider_dataset_id, native_variable_code)'
  LOOP EXECUTE format('ALTER TABLE ontology.indicator_aliases DROP CONSTRAINT %I',c.conname); END LOOP;
END $$;
CREATE UNIQUE INDEX IF NOT EXISTS alias_identity_version ON ontology.indicator_aliases
  (provider_id,provider_dataset_id,native_variable_code,version);
CREATE UNIQUE INDEX IF NOT EXISTS alias_single_successor ON ontology.indicator_aliases(previous_alias_id)
  WHERE previous_alias_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS ontology.alias_review_events (
  alias_id UUID NOT NULL REFERENCES ontology.indicator_aliases(alias_id) ON DELETE RESTRICT,
  event_version INTEGER NOT NULL CHECK(event_version>0),
  event_type TEXT NOT NULL CHECK(event_type IN ('baseline_import','registered','transition')),
  previous_state TEXT,
  new_state TEXT NOT NULL,
  reviewer_claim TEXT NOT NULL,
  evidence_reference TEXT,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  snapshot JSONB NOT NULL,
  PRIMARY KEY(alias_id,event_version)
);
-- On replay no inserts are attempted, so the immutable-event guard stays enabled.
INSERT INTO ontology.alias_review_events(alias_id,event_version,event_type,previous_state,new_state,
  reviewer_claim,evidence_reference,snapshot)
SELECT a.alias_id,1,'baseline_import',NULL,a.mapping_status,a.reviewed_by,a.approval_evidence,to_jsonb(a)
FROM ontology.indicator_aliases a WHERE NOT EXISTS
 (SELECT 1 FROM ontology.alias_review_events e WHERE e.alias_id=a.alias_id);

CREATE OR REPLACE FUNCTION ontology.guard_alias_event() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP<>'INSERT' OR pg_trigger_depth()<2 THEN
    RAISE EXCEPTION 'Alias review events are append-only and generated by alias transitions';
  END IF;
  RETURN NEW;
END $$;
CREATE OR REPLACE FUNCTION ontology.guard_alias_transition() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE prior ontology.indicator_aliases; successor ontology.indicator_aliases;
BEGIN
  IF TG_OP IN ('DELETE','TRUNCATE') THEN RAISE EXCEPTION 'Alias history cannot be deleted'; END IF;
  IF TG_OP='INSERT' THEN
    -- Preserve base CHECK-constraint diagnostics for invalid enum values.
    IF NEW.mapping_status NOT IN ('candidate','approved','deprecated','rejected','revoked','superseded') THEN RETURN NEW; END IF;
    IF NOT (NEW.unit_conversion_multiplier > '-Infinity'::float8 AND NEW.unit_conversion_multiplier < 'Infinity'::float8)
      OR NEW.unit_conversion_multiplier=0
      OR NOT (NEW.unit_conversion_offset > '-Infinity'::float8 AND NEW.unit_conversion_offset < 'Infinity'::float8) THEN
      RAISE EXCEPTION 'Alias conversion must be finite with nonzero multiplier';
    END IF;
    IF NEW.mapping_status<>'candidate' OR NEW.reviewed_by<>'unreviewed'
      OR NEW.reviewed_at IS NOT NULL OR NEW.approval_evidence IS NOT NULL
      OR NEW.revoked_by IS NOT NULL OR NEW.revoked_at IS NOT NULL
      OR NEW.revocation_reason IS NOT NULL OR NEW.superseded_by_alias_id IS NOT NULL THEN
      RAISE EXCEPTION 'New alias must be an unreviewed candidate';
    END IF;
    IF NEW.previous_alias_id IS NULL THEN
      IF NEW.version<>1 THEN RAISE EXCEPTION 'Initial alias version must be 1'; END IF;
    ELSE
      SELECT * INTO prior FROM ontology.indicator_aliases WHERE alias_id=NEW.previous_alias_id FOR UPDATE;
      IF NOT FOUND OR prior.mapping_status NOT IN ('approved','revoked','superseded','rejected')
        OR ROW(NEW.provider_id,NEW.provider_dataset_id,NEW.native_variable_code,NEW.canonical_code)
          IS DISTINCT FROM ROW(prior.provider_id,prior.provider_dataset_id,prior.native_variable_code,prior.canonical_code)
        OR NEW.version<>prior.version+1 THEN
        RAISE EXCEPTION 'Invalid alias revision identity, predecessor or version';
      END IF;
    END IF;
    RETURN NEW;
  END IF;
  -- Definitions and original attribution are immutable; revisions require new rows.
  IF (to_jsonb(NEW)-ARRAY['mapping_status','reviewed_by','reviewed_at','governance_review_notes',
      'approval_evidence','revoked_by','revoked_at','revocation_reason','superseded_by_alias_id'])
    IS DISTINCT FROM
    (to_jsonb(OLD)-ARRAY['mapping_status','reviewed_by','reviewed_at','governance_review_notes',
      'approval_evidence','revoked_by','revoked_at','revocation_reason','superseded_by_alias_id']) THEN
    RAISE EXCEPTION 'Alias definition is immutable; register a linked revision';
  END IF;
  IF NOT ((OLD.mapping_status='candidate' AND NEW.mapping_status IN ('approved','rejected'))
    OR (OLD.mapping_status='approved' AND NEW.mapping_status IN ('revoked','superseded'))) THEN
    RAISE EXCEPTION 'Invalid alias lifecycle transition: % -> %',OLD.mapping_status,NEW.mapping_status;
  END IF;
  IF OLD.mapping_status='candidate' THEN
    IF length(btrim(NEW.reviewed_by))<3 OR btrim(NEW.reviewed_by)='unreviewed'
      OR NEW.reviewed_at IS NULL OR length(btrim(NEW.governance_review_notes))<8
      OR NEW.revoked_by IS NOT NULL OR NEW.revoked_at IS NOT NULL OR NEW.revocation_reason IS NOT NULL
      OR NEW.superseded_by_alias_id IS NOT NULL THEN
      RAISE EXCEPTION 'Candidate decision requires reviewer claim, timestamp and detailed notes';
    END IF;
    IF NEW.mapping_status='approved' AND (NEW.approval_evidence IS NULL OR length(btrim(NEW.approval_evidence))<5) THEN
      RAISE EXCEPTION 'Approval requires evidence';
    END IF;
    IF NEW.mapping_status='rejected' AND NEW.approval_evidence IS NOT NULL THEN
      RAISE EXCEPTION 'Rejected candidate cannot carry approval evidence';
    END IF;
  ELSE
    IF ROW(NEW.reviewed_by,NEW.reviewed_at,NEW.governance_review_notes,NEW.approval_evidence)
      IS DISTINCT FROM ROW(OLD.reviewed_by,OLD.reviewed_at,OLD.governance_review_notes,OLD.approval_evidence)
      OR NEW.revoked_by IS NULL OR length(btrim(NEW.revoked_by))<3 OR btrim(NEW.revoked_by)='unreviewed'
      OR NEW.revoked_at IS NULL OR NEW.revocation_reason IS NULL OR length(btrim(NEW.revocation_reason))<8 THEN
      RAISE EXCEPTION 'Withdrawal must preserve approval and record reviewer claim and detailed reason';
    END IF;
    IF NEW.mapping_status='superseded' THEN
      SELECT * INTO successor FROM ontology.indicator_aliases WHERE alias_id=NEW.superseded_by_alias_id FOR UPDATE;
      IF NOT FOUND OR successor.mapping_status<>'approved' OR successor.reviewed_at IS NULL
        OR successor.approval_evidence IS NULL OR length(btrim(successor.approval_evidence))<5
        OR successor.previous_alias_id IS DISTINCT FROM OLD.alias_id
        OR successor.version<>OLD.version+1
        OR ROW(successor.provider_id,successor.provider_dataset_id,successor.native_variable_code,
          successor.canonical_code,successor.concept_equivalence_grade,
          successor.unit_conversion_multiplier,successor.unit_conversion_offset)
          IS DISTINCT FROM ROW(OLD.provider_id,OLD.provider_dataset_id,OLD.native_variable_code,
          OLD.canonical_code,OLD.concept_equivalence_grade,OLD.unit_conversion_multiplier,OLD.unit_conversion_offset) THEN
        RAISE EXCEPTION 'Supersession requires a reviewed compatible immediate successor';
      END IF;
    ELSIF NEW.superseded_by_alias_id IS NOT NULL THEN
      RAISE EXCEPTION 'Revocation cannot name a successor';
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE OR REPLACE FUNCTION ontology.record_alias_event() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE n integer;
BEGIN
  SELECT coalesce(max(event_version),0)+1 INTO n FROM ontology.alias_review_events WHERE alias_id=NEW.alias_id;
  INSERT INTO ontology.alias_review_events(alias_id,event_version,event_type,previous_state,new_state,
    reviewer_claim,evidence_reference,snapshot)
  VALUES(NEW.alias_id,n,CASE WHEN TG_OP='INSERT' THEN 'registered' ELSE 'transition' END,
    CASE WHEN TG_OP='UPDATE' THEN OLD.mapping_status ELSE NULL END,NEW.mapping_status,
    CASE WHEN NEW.mapping_status IN ('revoked','superseded') THEN NEW.revoked_by ELSE NEW.reviewed_by END,
    NEW.approval_evidence,to_jsonb(NEW));
  RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER alias_event_guard BEFORE INSERT OR UPDATE OR DELETE ON ontology.alias_review_events
  FOR EACH ROW EXECUTE FUNCTION ontology.guard_alias_event();
CREATE OR REPLACE TRIGGER alias_event_truncate_guard BEFORE TRUNCATE ON ontology.alias_review_events
  FOR EACH STATEMENT EXECUTE FUNCTION ontology.guard_alias_event();
CREATE OR REPLACE TRIGGER alias_transition_guard BEFORE INSERT OR UPDATE OR DELETE ON ontology.indicator_aliases
  FOR EACH ROW EXECUTE FUNCTION ontology.guard_alias_transition();
CREATE OR REPLACE TRIGGER alias_truncate_guard BEFORE TRUNCATE ON ontology.indicator_aliases
  FOR EACH STATEMENT EXECUTE FUNCTION ontology.guard_alias_transition();
CREATE OR REPLACE TRIGGER alias_record_event AFTER INSERT OR UPDATE ON ontology.indicator_aliases
  FOR EACH ROW EXECUTE FUNCTION ontology.record_alias_event();
COMMIT;
